def parse_batch_ids(text: str) -> list[str]:
    ids = []
    for token in re.split(r"[\s,]+", text or ""):
        token = token.strip()
        if not token or token.startswith("#"):
            continue
        if not BATCH_ID_RE.match(token):
            raise ValueError(f"Invalid batch id: {token!r}")
        if token not in ids:
            ids.append(token)
    if not ids:
        raise ValueError("No batch ids given")
    return ids


def write_batch_file(stage: str, batch_ids: list[str], stamp: str) -> Path:
    DASH_DIR.mkdir(parents=True, exist_ok=True)
    path = DASH_DIR / f"{stage}_{stamp}.batches.txt"
    path.write_text("".join(f"{b}\n" for b in batch_ids))
    return path


def _new_task(store: Store, kind: str, stage: str, items: list[str]) -> dict:
    task = {
        "id": uuid.uuid4().hex[:10], "kind": kind, "stage": stage, "batches": items,
        "status": "running", "created": utc_now(), "batch_file": None,
        "output": "", "job_id": None, "log": None,
        "stamp": datetime.now().strftime("%Y%m%d_%H%M%S"),
    }
    store.tasks[task["id"]] = task
    return task


def _start_local(task: dict, cmd: list[str]) -> str:
    threading.Thread(target=_run_preview, args=(task, cmd), daemon=True).start()
    return task["id"]


def _sbatch(task: dict, name: str, body: str, *, time_limit: str,
            cpus: int = 1, mem: str = "2G") -> str:
    if this_cluster() != "ceres":
        task.update(status="error", output=f"{name} must be submitted from ceres")
        return task["id"]
    base = DASH_DIR / f"{name}_{task['stamp']}_{task['id']}"
    log = f"{base}_%j.out"
    script = base.with_suffix(".sbatch")
    DASH_DIR.mkdir(parents=True, exist_ok=True)
    script.write_text(SBATCH_HEADER.format(
        name=name, cpus=cpus, mem=mem, time=time_limit, log=log,
        created=utc_now(), repo=REPO_ROOT,
    ) + body)
    try:
        proc = subprocess.run(
            ["sbatch", "--parsable", str(script)],
            cwd=REPO_ROOT, capture_output=True, text=True, timeout=60,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        task.update(status="error", output=str(exc))
        return task["id"]
    if proc.returncode != 0:
        task.update(status="error", output=proc.stderr or proc.stdout)
        return task["id"]
    job_id = proc.stdout.strip().split(";")[0]
    task.update(
        status="submitted", job_id=job_id, output=f"Submitted {script}\nSlurm job {job_id}",
        log=log.replace("%j", job_id),
    )
    logger.info("Submitted %s (%d item(s)): job %s", name, len(task["batches"]), job_id)
    return task["id"]


def run_task(store: Store, kind: str, stage: str, batch_ids: list[str], opts: dict) -> str:
    spec = STAGES[stage]
    task = _new_task(store, kind, stage, batch_ids)
    batch_file = write_batch_file(stage, batch_ids, f"{task['stamp']}_{task['id']}")
    task["batch_file"] = str(batch_file)
    site = opts.get("site") or spec["site"]
    rerun = bool(opts.get("rerun")) and stage in RERUN_STAGES

    if kind == "preview":
        return _start_local(task, [
            sys.executable, "scripts/job/stage_inputs.py", "--stage", stage,
            "--config", spec["config"], "--batches", str(batch_file), "--site", site,
            "--limit", str(max(50, len(batch_ids))), "--dry-run",
        ] + (["--rerun"] if rerun else []))

    if spec["cluster"] != this_cluster():
        task.update(status="error", output=f"{stage} must be submitted from {spec['cluster']}")
        return task["id"]
    return _sbatch(task, stage, STAGE_CHAIN_BODY.format(
        stage=stage, config=spec["config"], batches=batch_file, site=site,
        limit=max(50, len(batch_ids)), poll_limit=max(200, 10 * len(batch_ids)),
        rerun=" \\\n    --rerun" if rerun else "",
    ), time_limit=opts.get("time") or "12:00:00")


def run_sync_task(store: Store, action: str, opts: dict) -> str:
    """Preview/run sync_atlas_results.py, or check/publish the DB snapshot."""
    if action in ("sync_preview", "sync_run"):
        reopen = [r for r in opts.get("reopen", []) if RUN_ID_RE.match(r)]
        args = ["scripts/admin/sync_atlas_results.py", "--config", SYNC_CONFIG,
                "--bundle-limit", str(int(opts.get("bundle_limit") or 50))]
        if opts.get("refresh_inventory"):
            args.append("--refresh-inventory")
        task = _new_task(store, "preview" if action == "sync_preview" else "trigger",
                         "result_sync", reopen)
        if action == "sync_preview":
            # --reopen-run-id writes to SQLite, so it's never part of a dry run.
            return _start_local(task, [sys.executable, *args, "--dry-run"])
        for run_id in reopen:
            args += ["--reopen-run-id", run_id]
        # The inventory refresh after a promotion walks all of
        # semifield-developed-images with config'd max_workers.
        return _sbatch(task, "result_sync", COMMAND_BODY.format(
            label="sync_atlas_results", command="python " + " ".join(args),
        ), time_limit="6:00:00", cpus=8, mem="16G")

    if action in ("snapshot_check", "snapshot_publish"):
        args = ["scripts/admin/publish_ceres_db_snapshot.py", "--config", SYNC_CONFIG]
        task = _new_task(store, "check" if action == "snapshot_check" else "trigger",
                         "db_snapshot", [])
        # Even --dry-run backs up the full (~28 GB) DB to a candidate file
        # before reconciling, so both variants go to Slurm, not the login node.
        if action == "snapshot_check":
            args.append("--dry-run")
        elif opts.get("transfer"):
            args.append("--transfer")
        return _sbatch(task, "db_snapshot", COMMAND_BODY.format(
            label="publish_ceres_db_snapshot", command="python " + " ".join(args),
        ), time_limit="4:00:00", cpus=2, mem="8G")

    raise ValueError(f"Unknown sync action {action!r}")


def _run_preview(task: dict, cmd: list[str]) -> None:
    try:
        proc = subprocess.run(
            cmd, cwd=REPO_ROOT, capture_output=True, text=True, timeout=900,
        )
        task["output"] = (proc.stdout + proc.stderr)[-200_000:]
        task["status"] = "done" if proc.returncode == 0 else f"exit {proc.returncode}"
    except subprocess.TimeoutExpired:
        task.update(status="timeout", output="Preview exceeded 15 minutes.")
    except OSError as exc:
        task.update(status="error", output=str(exc))


