def load_or_create_token() -> str:
    """Reuse one token across restarts so the browser cookie keeps working."""
    try:
        token = TOKEN_FILE.read_text().strip()
        if token:
            return token
    except OSError:
        pass
    token = secrets.token_urlsafe(24)
    fd = os.open(TOKEN_FILE, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(token + "\n")
    return token


def write_state(state_file: Path, **state) -> None:
    """Record where the job-hosted dashboard is listening (for --connect)."""
    state_file.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(state_file, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        json.dump({**state, "updated": utc_now()}, fh, indent=1)


def connect(state_file: Path, local_port: int, token: str) -> int:
    """Relay localhost:<local_port> on the login node to the job's node:port.

    The job lands on a different compute node every day, which a laptop
    can't reach directly; this gives it a fixed localhost address that VS
    Code (or ``ssh -L``) forwards like any other login-node port.
    """
    import asyncio

    try:
        state = json.loads(state_file.read_text())
    except (OSError, ValueError):
        state = {}
    if not state.get("running"):
        print(f"No dashboard job is running (per {state_file}).\n"
              f"Start one: cd {REPO_ROOT} && sbatch scripts/admin/dashboard.sbatch", file=sys.stderr)
        return 1
    target = (state["host"], state["port"])
    try:
        socket.create_connection(target, timeout=10).close()
    except OSError as exc:
        print(f"Dashboard job {state.get('job_id')} recorded at {target[0]}:{target[1]} "
              f"but it isn't answering ({exc}). Check: squeue --name=agir_dashboard",
              file=sys.stderr)
        return 1

    async def pipe(reader, writer):
        try:
            while data := await reader.read(65536):
                writer.write(data)
                await writer.drain()
        except (ConnectionError, OSError):
            pass
        finally:
            writer.close()

    async def handle(client_r, client_w):
        try:
            node_r, node_w = await asyncio.open_connection(*target)
        except OSError:
            client_w.close()
            return
        await asyncio.gather(pipe(client_r, node_w), pipe(node_r, client_w))

    async def serve():
        for port in range(local_port, local_port + 20):
            try:
                server = await asyncio.start_server(handle, "127.0.0.1", port)
                break
            except OSError:
                continue
        else:
            print(f"Ports {local_port}-{local_port + 19} are all in use.", file=sys.stderr)
            return 1
        print(f"AgIR dashboard (job {state.get('job_id')} on {target[0]}, "
              f"up since {state.get('started')})\n\n"
              f"  http://localhost:{port}/?token={token}\n\n"
              f"From VS Code, click the link (it forwards the port). From a plain ssh\n"
              f"session, log in with: ssh -L {port}:localhost:{port} <user>@ceres.scinet.usda.gov\n"
              f"Ctrl-C closes this relay; the dashboard job keeps running.", flush=True)
        async with server:
            await server.serve_forever()

    try:
        return asyncio.run(serve()) or 0
    except KeyboardInterrupt:
        return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="AgIR pipeline operator dashboard.")
    parser.add_argument("--db", default=DEFAULT_DB, help=f"SQLite DB (default: {DEFAULT_DB}).")
    parser.add_argument("--port", type=int, default=8765,
                        help="Listen port (0 picks a free one); with --connect, the local port.")
    parser.add_argument(
        "--host", default="127.0.0.1",
        help="Bind address; the Slurm job uses 0.0.0.0 so --connect can reach it.",
    )
    parser.add_argument(
        "--token", default=os.environ.get("AGIR_DASHBOARD_TOKEN"),
        help=f"Access token (default: $AGIR_DASHBOARD_TOKEN, else {TOKEN_FILE}, "
             "created on first use).",
    )
    parser.add_argument(
        "--state-file", type=Path, default=STATE_FILE,
        help=f"Where the job records its node/port for --connect (default: {STATE_FILE}).",
    )
    parser.add_argument(
        "--advertise-host",
        help="Host name recorded in --state-file for this server (the job's node). "
             "Setting it makes this server write the state file.",
    )
    parser.add_argument(
        "--connect", action="store_true",
        help="On the login node: relay localhost:--port to the running dashboard job "
             "and print its URL.",
    )
    parser.add_argument(
        "--refresh-on-start", action="store_true",
        help="Recompute readiness views in the background at startup.",
    )
    parser.add_argument("--log-level", default="INFO",
                        choices=["DEBUG", "INFO", "WARNING", "ERROR"])
    args = parser.parse_args()
    logging.basicConfig(level=args.log_level, format="%(asctime)s %(levelname)s %(message)s")

    token = args.token or load_or_create_token()
    if args.connect:
        return connect(args.state_file, args.port, token)

    store = Store(args.db)
    if args.refresh_on_start or not store.readiness:
        store.refresh_readiness()

    server = ThreadingHTTPServer((args.host, args.port), make_handler(store, token))
    port = server.server_address[1]
    state = {"host": args.advertise_host, "port": port,
             "job_id": os.environ.get("SLURM_JOB_ID"), "started": utc_now()}
    if args.advertise_host:
        write_state(args.state_file, **state, running=True)
        # Job logs are group-readable; keep the token out of them.
        print(f"\nAgIR dashboard on {args.advertise_host}:{port}; "
              f"connect with: dashboard.py --connect\n", flush=True)
    else:
        print(f"\nAgIR dashboard: http://localhost:{port}/?token={token}\n", flush=True)

    def on_sigterm(signum, frame):
        raise KeyboardInterrupt

    # Slurm (time limit, scancel) and `timeout` stop the job with SIGTERM.
    signal.signal(signal.SIGTERM, on_sigterm)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
        if args.advertise_host:
            write_state(args.state_file, **state, running=False)
    return 0


if __name__ == "__main__":
    sys.exit(main())
