def make_handler(store: Store, token: str):
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, fmt, *args):
            logger.debug("%s " + fmt, self.address_string(), *args)

        def _cookie_token(self) -> str:
            cookies = SimpleCookie(self.headers.get("Cookie") or "")
            morsel = cookies.get(TOKEN_COOKIE)
            return morsel.value if morsel else ""

        def _authorized(self, query: dict) -> bool:
            supplied = (
                self.headers.get("X-Token")
                or (query.get("token") or [""])[0]
                or self._cookie_token()
            )
            return secrets.compare_digest(supplied, token)

        def _redirect_with_cookie(self):
            # VS Code port forwarding can drop the query string, so after one
            # authorized visit the token rides along in a cookie instead.
            self.send_response(303)
            self.send_header(
                "Set-Cookie",
                f"{TOKEN_COOKIE}={token}; Path=/; HttpOnly; SameSite=Strict; Max-Age=2592000",
            )
            self.send_header("Location", "./")
            self.send_header("Content-Length", "0")
            self.end_headers()

        def _send(self, code: int, body, ctype="application/json"):
            if not isinstance(body, (bytes, str)):
                body = json.dumps(body, default=str)
            if isinstance(body, str):
                body = body.encode()
            self.send_response(code)
            self.send_header("Content-Type", f"{ctype}; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)

        def do_GET(self):
            url = urlparse(self.path)
            q = parse_qs(url.query)
            if not self._authorized(q):
                if url.path == "/":
                    return self._send(403, LOGIN_PAGE, "text/html")
                return self._send(403, {"error": "forbidden"})
            try:
                if url.path == "/" and "token" in q:
                    return self._redirect_with_cookie()
                if url.path == "/":
                    return self._send(200, PAGE.replace("__DB__", html.escape(store.db_path)),
                                      "text/html")
                if url.path == "/api/overview":
                    return self._send(200, store.overview())
                if url.path == "/api/activity":
                    return self._send(200, store.activity())
                if url.path == "/api/batch":
                    return self._send(200, store.batch(parse_batch_ids(q["id"][0])[0]))
                if url.path == "/api/sync":
                    return self._send(200, store.sync_state())
                if url.path == "/api/history":
                    return self._send(200, {"jobs": sacct_history()})
                if url.path == "/api/task":
                    return self._send(200, store.tasks[q["id"][0]])
                if url.path == "/api/log":
                    return self._send(200, {"text": read_log_tail(q["path"][0])})
            except (KeyError, IndexError):
                return self._send(404, {"error": "not found"})
            except (ValueError, PermissionError, OSError) as exc:
                return self._send(400, {"error": str(exc)})
            self._send(404, {"error": "not found"})

        def do_POST(self):
            url = urlparse(self.path)
            if not self._authorized(parse_qs(url.query)):
                return self._send(403, {"error": "forbidden"})
            try:
                length = int(self.headers.get("Content-Length") or 0)
                body = json.loads(self.rfile.read(length) or b"{}")
                if url.path == "/api/refresh":
                    stages = [s for s in body.get("stages", STAGES) if s in STAGES]
                    return self._send(200, {"started": store.refresh_readiness(stages)})
                if url.path == "/api/sync":
                    task_id = run_sync_task(store, body.get("action"), body)
                    return self._send(200, store.tasks[task_id])
                if url.path in ("/api/preview", "/api/trigger"):
                    stage = body.get("stage")
                    if stage not in STAGES:
                        raise ValueError(f"Unknown stage {stage!r}")
                    kind = url.path.rsplit("/", 1)[1]
                    task_id = run_task(
                        store, kind, stage, parse_batch_ids(body.get("batches", "")), body
                    )
                    return self._send(200, store.tasks[task_id])
            except ValueError as exc:
                return self._send(400, {"error": str(exc)})
            self._send(404, {"error": "not found"})

    return Handler


