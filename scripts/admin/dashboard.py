class Store:
    def __init__(self, db_path: str):
        self.db_path = db_path
        self.lock = threading.Lock()
        self.readiness = self._load_cache()
        self.refreshing = False
        # In-memory preview/trigger tasks: id -> dict.
        self.tasks: dict[str, dict] = {}

    def connect(self):
        conn = open_db(self.db_path, readonly=True)
        # The indexer and ingest jobs write to this DB; wait instead of
        # failing with "database is locked".
        conn.execute("PRAGMA busy_timeout = 60000")
        return conn

    def query(self, sql: str, params=()) -> list[dict]:
        conn = self.connect()
        try:
            return [dict(r) for r in conn.execute(sql, params).fetchall()]
        finally:
            conn.close()

    # -- readiness cache ----------------------------------------------------

    def _load_cache(self) -> dict:
        try:
            cache = json.loads(READINESS_CACHE.read_text())
        except (OSError, ValueError):
            return {}
        # A refresh interrupted by a restart leaves this set.
        for entry in cache.values():
            entry["computing"] = False
        return cache

    def _save_cache(self) -> None:
        DASH_DIR.mkdir(parents=True, exist_ok=True)
        tmp = READINESS_CACHE.with_suffix(".tmp")
        tmp.write_text(json.dumps(self.readiness, indent=1))
        tmp.replace(READINESS_CACHE)

    def refresh_readiness(self, stages=None) -> bool:
        with self.lock:
            if self.refreshing:
                return False
            self.refreshing = True
        threading.Thread(
            target=self._refresh_worker, args=(list(stages or STAGES),), daemon=True
        ).start()
        return True

    def _refresh_worker(self, stages: list[str]) -> None:
        try:
            for stage in stages:
                entry = self.readiness.setdefault(stage, {})
                entry["computing"] = True
                t0 = time.monotonic()
                try:
                    rows = self.query(f"SELECT batch_id FROM v_batches_needing_{stage}")
                    entry.update(
                        batch_ids=sorted({r["batch_id"] for r in rows}),
                        error=None,
                        computed_at=utc_now(),
                        seconds=round(time.monotonic() - t0, 1),
                    )
                except Exception as exc:  # keep the previous list on failure
                    logger.warning("Readiness for %s failed: %s", stage, exc)
                    entry["error"] = str(exc)
                finally:
                    entry["computing"] = False
                    self._save_cache()
        finally:
            self.refreshing = False

    # -- live state -----------------------------------------------------------

    def overview(self) -> dict:
        runs = self.query(
            "SELECT stage, status, COUNT(*) AS n, MAX(ended_at) AS last_ended "
            "FROM stage_runs GROUP BY stage, status"
        )
        leases = self.query(
            "SELECT stage, "
            "SUM(expires_at > strftime('%Y-%m-%dT%H:%M:%SZ','now')) AS active, "
            "SUM(expires_at <= strftime('%Y-%m-%dT%H:%M:%SZ','now')) AS expired "
            "FROM stage_leases GROUP BY stage"
        )
        staging = self.query(
            "SELECT stage, status, COUNT(DISTINCT batch_id) AS n "
            "FROM staged_inputs GROUP BY stage, status"
        )
        out = {}
        here = this_cluster()
        for stage, spec in STAGES.items():
            ready = self.readiness.get(stage, {})
            out[stage] = {
                "cluster": spec["cluster"],
                "site": spec["site"],
                "config": spec["config"],
                "triggerable": spec["cluster"] == here,
                "rerun": stage in RERUN_STAGES,
                "runs": {r["status"]: r["n"] for r in runs if r["stage"] == stage},
                "last_run": max(
                    (r["last_ended"] for r in runs if r["stage"] == stage), default=None
                ),
                "leases": next(
                    ({"active": ls["active"] or 0, "expired": ls["expired"] or 0}
                     for ls in leases if ls["stage"] == stage),
                    {"active": 0, "expired": 0},
                ),
                "staging": {s["status"]: s["n"] for s in staging if s["stage"] == stage},
                "ready": {
                    "count": len(ready.get("batch_ids", [])) if "batch_ids" in ready else None,
                    "batch_ids": ready.get("batch_ids", []),
                    "computed_at": ready.get("computed_at"),
                    "computing": ready.get("computing", False),
                    "seconds": ready.get("seconds"),
                    "error": ready.get("error"),
                },
            }
        return {"stages": out, "cluster": here, "refreshing": self.refreshing}

    def activity(self) -> dict:
        now_sql = "strftime('%Y-%m-%dT%H:%M:%SZ','now')"
        return {
            "recent_runs": self.query(
                "SELECT run_id, batch_id, stage, status, exit_code, started_at, ended_at, "
                "duration_ms, n_units_discovered, n_units_succeeded, n_units_failed, run_root "
                "FROM stage_runs ORDER BY ended_at DESC LIMIT 40"
            ),
            "leases": self.query(
                f"SELECT batch_id, stage, orchestrator_id, claimed_at, expires_at, slurm_job_id, "
                f"expires_at > {now_sql} AS active "
                f"FROM stage_leases ORDER BY claimed_at DESC"
            ),
            "staging": self.query(
                "SELECT batch_id, stage, status, globus_task_id, error_summary, updated_at "
                "FROM staged_inputs "
                "WHERE status NOT IN ('completed', 'canceled') "
                "ORDER BY updated_at DESC LIMIT 100"
            ),
            "jobs": squeue_jobs(),
            "tasks": sorted(
                ({k: v for k, v in t.items() if k != "output"} for t in self.tasks.values()),
                key=lambda t: t["created"],
                reverse=True,
            ),
        }

    def sync_state(self) -> dict:
        try:
            cfg = yaml.safe_load((REPO_ROOT / SYNC_CONFIG).read_text())
            inbox = Path(cfg["result_sync"]["ceres_inbox"])
            snapshot = Path(cfg["snapshot"]["ceres_publish_path"])
        except (OSError, KeyError, TypeError, yaml.YAMLError) as exc:
            return {"error": f"Can't read {SYNC_CONFIG}: {exc}"}

        known = {r["run_id"] for r in self.query("SELECT run_id FROM result_syncs")}
        try:
            inbox_ids = [f.name.split(".", 1)[0] for f in inbox.glob("*.result-sync.json")]
        except OSError:
            inbox_ids = []
        try:
            st = snapshot.stat()
            snap = {"path": str(snapshot), "mtime": datetime.fromtimestamp(
                st.st_mtime, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "size": st.st_size}
        except OSError:
            snap = {"path": str(snapshot), "mtime": None, "size": None}

        return {
            "config": SYNC_CONFIG,
            "states": SYNC_STATES,
            "counts": self.query(
                "SELECT stage, status, COUNT(*) AS n FROM result_syncs GROUP BY stage, status"
            ),
            "outstanding": self.query(
                "SELECT run_id, batch_id, stage, run_status, status, attempt_count, "
                "globus_task_id, error_summary, updated_at FROM result_syncs "
                "WHERE status != 'ingested' ORDER BY updated_at DESC LIMIT 200"
            ),
            "recent": self.query(
                "SELECT run_id, batch_id, stage, run_status, promotion_succeeded, ingested_at "
                "FROM result_syncs WHERE status = 'ingested' "
                "ORDER BY ingested_at DESC LIMIT 25"
            ),
            "inbox": {"path": str(inbox), "files": len(inbox_ids),
                      "unregistered": sorted(set(inbox_ids) - known)},
            "snapshot": snap,
        }

    def batch(self, batch_id: str) -> dict:
        p = (batch_id,)
        return {
            "batch_id": batch_id,
            "runs": self.query(
                "SELECT run_id, stage, status, exit_code, started_at, ended_at, duration_ms, "
                "n_units_discovered, n_units_succeeded, n_units_failed, run_root, logs_path "
                "FROM stage_runs WHERE batch_id = ? ORDER BY ended_at DESC",
                p,
            ),
            "leases": self.query("SELECT * FROM stage_leases WHERE batch_id = ?", p),
            "staging": self.query(
                "SELECT stage, status, src_path, dst_path, globus_task_id, error_summary, "
                "updated_at FROM staged_inputs WHERE batch_id = ? ORDER BY updated_at DESC",
                p,
            ),
            "syncs": self.query(
                "SELECT run_id, stage, status, run_status, error_summary, updated_at "
                "FROM result_syncs WHERE batch_id = ? ORDER BY updated_at DESC",
                p,
            ),
            "ready_for": [
                s for s, e in self.readiness.items() if batch_id in e.get("batch_ids", [])
            ],
        }


def squeue_jobs() -> list[dict]:
    fields = ["job_id", "name", "state", "time", "start", "reason", "partition", "stdout"]
    try:
        out = subprocess.run(
            ["squeue", "-u", os.environ.get("USER", ""), "-h", "-O",
             "JobID:|,Name:|,State:|,TimeUsed:|,StartTime:|,Reason:|,Partition:|,STDOUT:"],
            capture_output=True, text=True, timeout=20, check=True,
        ).stdout
    except (OSError, subprocess.SubprocessError) as exc:
        return [{"error": str(exc)}]
    jobs = []
    for line in out.splitlines():
        parts = [p.strip() for p in line.split("|")]
        if len(parts) < len(fields):
            continue
        job = dict(zip(fields, parts))
        job["stdout"] = expand_slurm_path(job["stdout"], job["job_id"], job["name"])
        jobs.append(job)
    return jobs


def expand_slurm_path(path: str, job_id: str, name: str) -> str:
    """Fill in the sbatch --output/--error placeholders the dashboard sees."""
    array_job, _, array_task = job_id.partition("_")
    return (path.replace("%j", job_id).replace("%x", name)
            .replace("%u", os.environ.get("USER", ""))
            .replace("%A", array_job).replace("%a", array_task))


def sacct_history(hours: int = 48) -> list[dict]:
    """The user's jobs (not steps) that started or ran in the last `hours`."""
    fields = ["job_id", "job_id_raw", "name", "state", "start", "end", "elapsed",
              "exit_code", "nodes", "stdout", "stderr"]
    since = (datetime.now() - timedelta(hours=hours)).strftime("%Y-%m-%dT%H:%M:%S")
    try:
        out = subprocess.run(
            ["sacct", "-u", os.environ.get("USER", ""), "-X", "-n", "--parsable2",
             "--starttime", since,
             "-o", "JobID,JobIDRaw,JobName,State,Start,End,Elapsed,ExitCode,NodeList,"
                   "StdOut,StdErr"],
            capture_output=True, text=True, timeout=30, check=True,
        ).stdout
    except (OSError, subprocess.SubprocessError) as exc:
        return [{"error": str(exc)}]
    jobs = []
    for line in out.splitlines():
        parts = line.split("|")
        if len(parts) != len(fields):
            continue
        job = dict(zip(fields, parts))
        # Never started (still queued, or cancelled while pending).
        if job["state"] == "PENDING" or job["start"] in ("None", "Unknown", ""):
            continue
        # "CANCELLED by 12345" -> CANCELLED, so the state filter/colour works.
        job["state"] = job["state"].split()[0]
        for key in ("stdout", "stderr"):
            path = expand_slurm_path(job[key], job["job_id"], job["name"])
            # Only link logs that exist (rotated/deleted ones would just error).
            job[key] = path if path and os.path.isfile(path) else ""
        jobs.append(job)
    jobs.sort(key=lambda j: j["start"], reverse=True)
    return jobs


def read_log_tail(path: str, lines: int = 300) -> str:
    p = Path(path).resolve()
    if not any(p.is_relative_to(root) for root in LOG_READ_ROOTS):
        raise PermissionError(f"Refusing to read outside {', '.join(map(str, LOG_READ_ROOTS))}")
    with p.open("rb") as fh:
        fh.seek(0, os.SEEK_END)
        size = fh.tell()
        fh.seek(max(0, size - 256 * 1024))
        data = fh.read().decode("utf-8", errors="replace")
    return "\n".join(data.splitlines()[-lines:])


